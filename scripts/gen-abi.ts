// Copies the Refuel ABI from Foundry's build output into the app.
// Usage: (cd contracts && forge build) && pnpm abi
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const artifact = JSON.parse(readFileSync(resolve(root, "contracts/out/Refuel.sol/Refuel.json"), "utf8"));
const out = resolve(root, "app/src/lib/abi/refuel.ts");
writeFileSync(
  out,
  `// Generated by scripts/gen-abi.ts from contracts/out/Refuel.sol/Refuel.json. Do not edit.\n` +
    `export const refuelAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
console.log(`wrote ${out} (${artifact.abi.length} entries)`);
